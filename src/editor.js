class NavWidget extends WidgetType {
  eq() { return true; }
  toDOM() {
    const el = document.createElement("div");
    el.className = "cm-nav";
    el.append(icon("lock"), "Navigation box · generated by a script, so it can't be edited here");
    return el;
  }
  ignoreEvent() { return false; }
}

const navRange = (doc) => findNavBlock(doc.toString());

const navDecorations = (nav) => nav
  ? Decoration.set([Decoration.replace({ widget: new NavWidget(), block: true }).range(nav.from, nav.to)])
  : Decoration.none;

/**
 * The navigation box shows folded and nothing can change it: no deleting into it, no typing inside
 * it, and no joining its first or last line with the line next to it.
 */
const navField = StateField.define({
  create: (state) => navRange(state.doc),
  update: (nav, tr) => (tr.docChanged ? navRange(tr.state.doc) : nav),
  provide: (f) => [
    EditorView.decorations.from(f, navDecorations),
    EditorView.atomicRanges.of((view) => navDecorations(view.state.field(f))),
  ],
});

const navGuard = EditorState.changeFilter.of((tr) => {
  const nav = tr.startState.field(navField, false);
  if (!nav || !tr.docChanged) return true;
  let ok = true;
  tr.changes.iterChanges((fromA, toA) => {
    const deletes = toA > fromA && fromA < nav.to + 1 && toA > nav.from - 1;
    const insertsInside = fromA >= nav.from && fromA <= nav.to;
    if (deletes || insertsInside) ok = false;
  });
  return ok;
});

export const protectNavBox = [navField, navGuard];

/** Underlines `[[links]]`, in red when they lead to no page. */
function linkMarks(resolve) {
  const decorator = new MatchDecorator({
    regexp: /!?\[\[([^\]\n]+)\]\]/g,
    decoration: (m) => {
      const { target } = parseWikilink(m[1]);
      return Decoration.mark({ class: !target || resolve(target) ? "cm-wikilink" : "cm-wikilink cm-missing" });
    },
  });
  return ViewPlugin.define((view) => ({
    decorations: decorator.createDeco(view),
    update(u) { this.decorations = decorator.updateDeco(u, this.decorations); },
  }), { decorations: (v) => v.decorations });
}

