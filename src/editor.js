/** A Markdown (or plain text) editor. `onChange(text)` runs on every edit. */
/**
 * Typing `@` offers the vault's people (`people()` gives [{ login, name }], maybe later); picking one writes
 * `@login`. Not right after a letter, a digit or `.+-_/@`, so an email doesn't open it.
 */
function mentionPicker(people) {
  return autocompletion({
    icons: false,
    override: [async (ctx) => {
      const word = ctx.matchBefore(/@[A-Za-z0-9-]*/);
      if (!word) return null;
      const before = ctx.state.sliceDoc(Math.max(0, word.from - 1), word.from);
      if (before && /[\p{L}\p{N}.+\-_/@`]/u.test(before)) return null;
      const list = await people().catch(() => []);
      if (!list.length) return null;
      return {
        from: word.from,
        options: list.map((p) => ({ label: `@${p.login}`, detail: p.name !== p.login ? p.name : undefined, apply: `@${p.login}` })),
        validFor: /^@[A-Za-z0-9-]*$/,
      };
    }],
  });
}

export function createEditor(parent, text, { onChange, resolve, isMarkdown = true, language = null, vault = false, readOnly = false, people = null, extra = [] } = {}) {
  return new EditorView({
    parent,
    state: EditorState.create({
      doc: text,
      extensions: [
        baseExtensions(),
        isMarkdown ? [yamlFrontmatter({ content: markdown({ base: markdownLanguage }) }), linkMarks(resolve)] : [],
        !isMarkdown && language ? [language.extension, EditorView.contentAttributes.of({ spellcheck: "false", autocapitalize: "off" })] : [],
        vault ? protectNavBox : [],
        isMarkdown && people && !readOnly ? mentionPicker(people) : [],
        readOnly ? [EditorState.readOnly.of(true), EditorView.editable.of(false)] : [],
        EditorView.updateListener.of((u) => { if (u.docChanged) onChange?.(u.state.doc.toString()); }),
        extra,
      ],
    }),
  });
}

/** The compact comment field uses the note editor's people picker. */
export function createCommentEditor(parent, text, people) {
  return new EditorView({
    parent,
    state: EditorState.create({
      doc: text,
      selection: { anchor: text.length },
      extensions: [
        history(), EditorView.lineWrapping, theme,
        keymap.of([...defaultKeymap, ...historyKeymap]),
        EditorView.contentAttributes.of({ "aria-label": "Write a comment", spellcheck: "true", autocapitalize: "sentences" }),
        placeholder("Write a comment…"),
        mentionPicker(people),
      ],
    }),
  });
}

/** Replaces the text from outside (a ticked checkbox, a restored draft); the nav guard doesn't apply. */
export function setEditorText(view, text) {
  if (view.state.doc.toString() === text) return;
  view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: text }, filter: false });
}

/** Their version on the left (read-only), mine on the right (editable). */
export function createMergeView(parent, theirs, mine, { vault = false } = {}) {
  return new MergeView({
    parent,
    a: { doc: theirs, extensions: [baseExtensions(), EditorState.readOnly.of(true), EditorView.editable.of(false)] },
    b: { doc: mine, extensions: [baseExtensions(), vault ? protectNavBox : []] },
    collapseUnchanged: { margin: 3, minSize: 6 },
  });
}
