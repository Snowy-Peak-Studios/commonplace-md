// CodeMirror 6, set up for notes.

import {
  EditorState, EditorView, StateField, keymap, Decoration, ViewPlugin, WidgetType, MatchDecorator,
  drawSelection, highlightActiveLine, defaultKeymap, history, historyKeymap, indentWithTab,
  searchKeymap, highlightSelectionMatches, syntaxHighlighting, HighlightStyle, markdown, markdownLanguage,
  MergeView, tags as t, yamlFrontmatter,
} from "../vendor/vendor.js";
import { findNavBlock, parseWikilink } from "./vault.js";
import { icon } from "./icons.js";

class NavWidget extends WidgetType {
  eq() { return true; }
  toDOM() {
    const el = document.createElement("div");
    el.className = "cm-nav";
    el.append(icon("lock"), "Navigation box · generated by a script, so it can't be edited here");
    return el;
  }
  ignoreEvent() { return false; }
}

const navRange = (doc) => findNavBlock(doc.toString());

const navDecorations = (nav) => nav
  ? Decoration.set([Decoration.replace({ widget: new NavWidget(), block: true }).range(nav.from, nav.to)])
  : Decoration.none;

/**
 * The navigation box shows folded and nothing can change it: no deleting into it, no typing inside
 * it, and no joining its first or last line with the line next to it.
 */
const navField = StateField.define({
  create: (state) => navRange(state.doc),
  update: (nav, tr) => (tr.docChanged ? navRange(tr.state.doc) : nav),
  provide: (f) => [
    EditorView.decorations.from(f, navDecorations),
    EditorView.atomicRanges.of((view) => navDecorations(view.state.field(f))),
  ],
});

const navGuard = EditorState.changeFilter.of((tr) => {
  const nav = tr.startState.field(navField, false);
  if (!nav || !tr.docChanged) return true;
  let ok = true;
  tr.changes.iterChanges((fromA, toA) => {
    const deletes = toA > fromA && fromA < nav.to + 1 && toA > nav.from - 1;
    const insertsInside = fromA >= nav.from && fromA <= nav.to;
    if (deletes || insertsInside) ok = false;
  });
  return ok;
});

export const protectNavBox = [navField, navGuard];

/** Underlines `[[links]]`, in red when they lead to no page. */
function linkMarks(resolve) {
  const decorator = new MatchDecorator({
    regexp: /!?\[\[([^\]\n]+)\]\]/g,
    decoration: (m) => {
      const { target } = parseWikilink(m[1]);
      return Decoration.mark({ class: !target || resolve(target) ? "cm-wikilink" : "cm-wikilink cm-missing" });
    },
  });
  return ViewPlugin.define((view) => ({
    decorations: decorator.createDeco(view),
    update(u) { this.decorations = decorator.updateDeco(u, this.decorations); },
  }), { decorations: (v) => v.decorations });
}

const highlight = HighlightStyle.define([
  { tag: t.heading1, fontSize: "1.45em", fontWeight: "700" },
  { tag: t.heading2, fontSize: "1.25em", fontWeight: "700" },
  { tag: t.heading3, fontSize: "1.1em", fontWeight: "700" },
  { tag: [t.heading4, t.heading5, t.heading6], fontWeight: "700" },
  { tag: t.strong, fontWeight: "700" },
  { tag: t.emphasis, fontStyle: "italic" },
  { tag: t.strikethrough, textDecoration: "line-through" },
  { tag: [t.link, t.url], color: "var(--accent)" },
  { tag: t.monospace, fontFamily: "var(--mono)", color: "var(--code)" },
  { tag: [t.processingInstruction, t.meta, t.quote], color: "var(--muted)" },
  { tag: t.list, color: "var(--accent)" },
]);

/** Colours from the page's own light and dark tokens, so the editor follows the page. */
const theme = EditorView.theme({
  "&": { color: "var(--text)", backgroundColor: "transparent" },
  ".cm-content": { caretColor: "var(--text)" },
  ".cm-cursor, .cm-dropCursor": { borderLeftColor: "var(--text)" },
  ".cm-activeLine": { backgroundColor: "var(--active-line)" },
  "&.cm-focused .cm-selectionBackground, .cm-selectionBackground, .cm-content ::selection": { backgroundColor: "var(--selection) !important" },
  ".cm-selectionMatch": { backgroundColor: "var(--selection-match)" },
  ".cm-searchMatch": { backgroundColor: "var(--selection-match)", outline: "1px solid var(--accent)" },
  ".cm-panels": { backgroundColor: "var(--bg-soft)", color: "var(--text)" },
  ".cm-gutters": { backgroundColor: "transparent", border: "none", color: "var(--muted)" },
  ".cm-changeGutter": { width: "3px", paddingLeft: "0" },
  ".cm-panels.cm-panels-bottom": { borderTop: "1px solid var(--line)" },
  ".cm-textfield": { backgroundColor: "var(--bg)", color: "var(--text)", border: "1px solid var(--line)" },
  ".cm-button": { backgroundImage: "none", backgroundColor: "var(--bg-soft)", color: "var(--text)", border: "1px solid var(--line)" },
});

const baseExtensions = () => [
  history(),
  drawSelection(),
  highlightActiveLine(),
  highlightSelectionMatches(),
  EditorView.lineWrapping,
  keymap.of([...defaultKeymap, ...historyKeymap, ...searchKeymap, indentWithTab]),
  syntaxHighlighting(highlight),
  theme,
  EditorView.contentAttributes.of({ spellcheck: "true", autocapitalize: "sentences" }),
];

/** A Markdown (or plain text) editor. `onChange(text)` runs on every edit. */
export function createEditor(parent, text, { onChange, resolve, isMarkdown = true, vault = false, readOnly = false, extra = [] } = {}) {
  return new EditorView({
    parent,
    state: EditorState.create({
      doc: text,
      extensions: [
        baseExtensions(),
        isMarkdown ? [yamlFrontmatter({ content: markdown({ base: markdownLanguage }) }), linkMarks(resolve)] : [],
        vault ? protectNavBox : [],
        readOnly ? [EditorState.readOnly.of(true), EditorView.editable.of(false)] : [],
        EditorView.updateListener.of((u) => { if (u.docChanged) onChange?.(u.state.doc.toString()); }),
        extra,
      ],
    }),
  });
}

/** Replaces the text from outside (a ticked checkbox, a restored draft); the nav guard doesn't apply. */
export function setEditorText(view, text) {
  if (view.state.doc.toString() === text) return;
  view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: text }, filter: false });
}

/** Their version on the left (read-only), mine on the right (editable). */
export function createMergeView(parent, theirs, mine, { vault = false } = {}) {
  return new MergeView({
    parent,
    a: { doc: theirs, extensions: [baseExtensions(), EditorState.readOnly.of(true), EditorView.editable.of(false)] },
    b: { doc: mine, extensions: [baseExtensions(), vault ? protectNavBox : []] },
    collapseUnchanged: { margin: 3, minSize: 6 },
  });
}
